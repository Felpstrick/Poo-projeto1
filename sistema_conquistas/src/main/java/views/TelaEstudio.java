        //Instanciar um objeito de estudio (model.bean)
        Estudio meuEstudio = new Estudio();
        
        //definir os valores dos atributos a partir do formulário
        meuEstudio.setNome(txtNome.getText());
        meuEstudio.setPais(txtPais.getText());
