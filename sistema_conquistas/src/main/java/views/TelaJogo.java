    //método para limpar a tela
    public void limpar(){
        txtTitulo.setText("");
        txtGenero.setText("");
        
        tblCadastrados.clearSelection();
        
        btnSalvar.setEnabled(true);
        btnEditar.setEnabled(false);
        btnExcluir.setEnabled(false);
    }
    
    public void preencherTabela(){
        DefaultTableModel dtm = (DefaultTableModel) tblCadastrados.getModel();
        dtm.setRowCount(0);
        JogoDAO dao = new JogoDAO();
        
        for(Jogo e : dao.read()){
            dtm.addRow(new Object[]{
                e.getId(),
                e.getTitulo(),
                e.getGenero(),
                e.getEstudio(),
                e.getDistribuidora()
                
            });
        }
    }
    
    public void preencherComboEstudio(){
        EstudioDAO dao = new EstudioDAO();
        
        for(Estudio e: dao.read()){
            cmbEstudio.addItem(e);
        }
    }
    
    public void preecherComboDistribuidora(){
        DistribuidoraDAO dao = new DistribuidoraDAO();
        
        for(Distribuidora d: dao.read()){
            cmbDistribuidora.addItem(d);
        }
    }
    

