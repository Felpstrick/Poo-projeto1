    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        //Instanciar um objeito de estudio (model.bean)
        Jogo meuJogo = new Jogo();
        
        //definir os valores dos atributos a partir do formulário
        meuJogo.setTitulo(txtTitulo.getText());
        meuJogo.setGenero(txtGenero.getText());
        meuJogo.setEstudio((Estudio) cmbEstudio.getSelectedItem());
        meuJogo.setDistribuidora((Distribuidora) cmbDistribuidora.getSelectedItem());
        
        //Instanciar objeto da classe EstudioDAO
        JogoDAO dao = new JogoDAO();
        dao.create(meuJogo);
        
        limpar();
        preencherTabela();
        
    }//GEN-LAST:event_btnSalvarActionPerformed

