    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // TODO add your handling code here:
        //Instanciar um objeito de estudio (model.bean)
        Usuario meuUsuario = new Usuario();
        
        //definir os valores dos atributos a partir do formulário
        meuUsuario.setNickname(txtNickname.getText());
        meuUsuario.setEmail(txtEmail.getText());
        
        //Instanciar objeto da classe EstudioDAO
        UsuarioDAO dao = new UsuarioDAO();
        dao.create(meuUsuario);
        
        limpar();
        preencherTabela();
        
    }//GEN-LAST:event_btnSalvarActionPerformed

